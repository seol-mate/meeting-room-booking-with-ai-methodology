-- 초기 스키마 — 근거: ERD-overview(4-DN-14-O1), ERD-meeting-room·ERD-reservation(4-DN-14-O2)
-- 감사 컬럼 4개(created_at, updated_at, created_by, updated_by)는 모든 테이블 공통(BaseEntity)

-- 같은 회의실의 예약 시간 겹침 배제 제약(ex_reservation_overlap)에 필요
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE reserver (
    reserver_id   bigint GENERATED BY DEFAULT AS IDENTITY,
    login_id      varchar(50)  NOT NULL,
    password_hash varchar(255) NOT NULL,
    name          varchar(100) NOT NULL,
    role          varchar(20)  NOT NULL DEFAULT 'USER',
    created_at    timestamp    NOT NULL,
    updated_at    timestamp    NOT NULL,
    created_by    bigint,
    updated_by    bigint,
    CONSTRAINT pk_reserver PRIMARY KEY (reserver_id),
    CONSTRAINT uk_reserver_login_id UNIQUE (login_id),
    CONSTRAINT ck_reserver_role CHECK (role IN ('USER', 'ROOM_MANAGER'))
);

CREATE TABLE meeting_room (
    meeting_room_id bigint GENERATED BY DEFAULT AS IDENTITY,
    name            varchar(100) NOT NULL,
    location        varchar(200),
    capacity        integer,
    equipment       varchar(500),
    created_at      timestamp    NOT NULL,
    updated_at      timestamp    NOT NULL,
    created_by      bigint,
    updated_by      bigint,
    CONSTRAINT pk_meeting_room PRIMARY KEY (meeting_room_id)
);

CREATE TABLE reservation (
    reservation_id  bigint GENERATED BY DEFAULT AS IDENTITY,
    meeting_room_id bigint       NOT NULL,
    reserver_id     bigint       NOT NULL,
    start_at        timestamp    NOT NULL,
    end_at          timestamp    NOT NULL,
    title           varchar(200),
    status          varchar(20)  NOT NULL DEFAULT 'RESERVED',
    cancelled_at    timestamp,
    cancelled_by    bigint,
    created_at      timestamp    NOT NULL,
    updated_at      timestamp    NOT NULL,
    created_by      bigint,
    updated_by      bigint,
    CONSTRAINT pk_reservation PRIMARY KEY (reservation_id),
    CONSTRAINT fk_reservation_meeting_room FOREIGN KEY (meeting_room_id) REFERENCES meeting_room (meeting_room_id),
    CONSTRAINT fk_reservation_reserver FOREIGN KEY (reserver_id) REFERENCES reserver (reserver_id),
    CONSTRAINT ck_reservation_status CHECK (status IN ('RESERVED', 'CANCELLED')),
    CONSTRAINT ck_reservation_period CHECK (end_at > start_at),
    CONSTRAINT ex_reservation_overlap EXCLUDE USING gist (
        meeting_room_id WITH =,
        tsrange(start_at, end_at) WITH &&
    ) WHERE (status = 'RESERVED')
);

CREATE INDEX idx_reservation_reserver ON reservation (reserver_id);
